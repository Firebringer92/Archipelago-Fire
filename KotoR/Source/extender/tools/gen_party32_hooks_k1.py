"""Generates extender/src_k1se/party32_hooks_generated.h from the Patch Manager K1 hook table.

Usage (from the project root):
    python -I extender/tools/gen_party32_hooks_k1.py <decrypted .text dump> [--out <header>]

The hook table is research/patchmanager_k1/upstream/kotor1.hooks.toml (MIT, Vriff / Patch Manager contributors). Every site's original bytes are compared with the decrypted code of the
Steam swkotor.exe (dump made by research/patchmanager_k1/tools/k1_memdump.py); the header is not written if any site differs.
"""
import os
import sys
import tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TOML = os.path.join(ROOT, "research", "patchmanager_k1", "upstream", "kotor1.hooks.toml")
OUT = os.path.join(ROOT, "extender", "src_k1se", "party32_hooks_generated.h")
TEXT_BASE = 0x401000

# Handlers that belong to the paged party-selection screen (applied only when the screen port is enabled).
GUI = {
    "PreparePartySelectionOnDone", "PreparePartySelectionAccept", "FinishPartySelectionAccept", "PrepareSetForcedNPC32",
    "FinishPartySelectionLayout", "PreparePartySelectionDestructor", "PreparePartySelectionOnPanelAdded",
    "FinishPartySelectionOnPanelAdded", "PreparePartySelectionOnPanelRemoved", "FinishPartySelectionOnPanelRemoved",
    "AdjustPartySelectionAfterObjectRemoval", "ClearPartySelectionForcedFlags",
}
REG = {"eax": 0, "ecx": 1, "edx": 2, "ebx": 3, "ebp": 4, "esi": 5, "edi": 6}


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    out = OUT
    if "--out" in sys.argv:
        out = sys.argv[sys.argv.index("--out") + 1]
        args = [a for a in args if a != out]
    dump = open(args[0], "rb").read()
    hooks = tomllib.load(open(TOML, "rb"))["hooks"]
    problems = []
    lines = []
    sites = []
    for i, h in enumerate(hooks):
        orig = bytes(h["original_bytes"])
        off = h["address"] - TEXT_BASE
        if dump[off:off + len(orig)] != orig:
            problems.append("hook %d at 0x%08X does not match the game code" % (i, h["address"]))
        lines.append("static const uint8_t kOrig%d[] = {%s};" % (i, ", ".join("0x%02X" % b for b in orig)))
        simple = h["type"] == "simple"
        argl = []
        for p in h.get("parameters", []):
            s = p["source"]
            if s in REG:
                argl.append("{%d, 0}" % REG[s])
            elif s.startswith("esp+"):
                argl.append("{7, %d}" % int(s[4:]))
            else:
                problems.append("hook %d: unknown parameter source %s" % (i, s))
        if len(argl) > 4:
            problems.append("hook %d has more than 4 parameters" % i)
        func = h.get("function", "")
        site = "    {%d, 0x%08X, %d, kOrig%d, %s, %s, \"%s\", {%s}, %d, %s, %s, 0x%08X, %s}," % (
            i, h["address"], len(orig), i,
            ("0x%02X" % h["replacement_bytes"][0]) if simple else "0x00",
            "true" if simple else "false", func, ", ".join(argl), len(argl),
            "true" if h.get("skip_original_bytes") else "false",
            "true" if "eax" in h.get("exclude_from_restore", []) else "false",
            h.get("consumed_exit_address", 0), "true" if func in GUI else "false")
        if simple and len(h["replacement_bytes"]) != 1:
            problems.append("hook %d: simple patches are one byte" % i)
        sites.append(site)
    if problems:
        print("NOT written:\n  " + "\n  ".join(problems))
        sys.exit(1)
    text = """// GENERATED by extender/tools/gen_party32_hooks_k1.py from research/patchmanager_k1/upstream/kotor1.hooks.toml (Patch Manager, MIT, Vriff and contributors),
// checked byte for byte against the decrypted Steam swkotor.exe. Do not edit by hand.
#pragma once
#include <stdint.h>

namespace party32 {

struct ArgSpec { uint8_t kind; int8_t offset; };   // kind: 0 eax, 1 ecx, 2 edx, 3 ebx, 4 ebp, 5 esi, 6 edi, 7 stack argument at esp+offset

struct Site {
    int number;                 // index in the hook table
    uint32_t address;
    uint16_t length;
    const uint8_t* original;
    uint8_t replacement;        // simple one-byte patches
    bool simple;
    const char* handler;        // detours: name of the handler
    ArgSpec args[4];
    uint8_t argCount;
    bool skipOriginal;
    bool resultEax;
    uint32_t consumedExit;      // nonzero: a nonzero handler result jumps here
    bool gui;                   // belongs to the paged party-selection screen
};

""" + "\n".join(lines) + "\n\nstatic const Site kSites[] = {\n" + "\n".join(sites) + "\n};\nstatic const int kSiteCount = %d;\n\n}  // namespace party32\n" % len(hooks)
    with open(out, "w", newline="\n") as f:
        f.write(text)
    print("wrote", out, "with", len(hooks), "sites, all matching the game code")


main()
