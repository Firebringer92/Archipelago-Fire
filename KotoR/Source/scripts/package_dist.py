def collect_expected_resrefs():
    """Every Override resref the always-on base layer needs, derived from
    the same data the generator scripts themselves use -- never hand-typed,
    so this can't silently drift out of sync with what actually gets
    generated."""
    resrefs = set(ALWAYS_ON_EXTRA) | set(HAND_WRITTEN_EXTRA)

    with open(MAPPING_PATH, encoding="utf-8") as f:
        mapping = json.load(f)
    for entry in mapping.values():
        resrefs.add(entry["onenter"])
        resrefs.add(entry["renamed"])

    for name, module, resref, npc_const, diag_code, npc_idx in COMPANIONS:
        resrefs.add(f"apo_{name}_orig")
        resrefs.add(resref)

    for idx, (module, resref) in enumerate(STORES):
        resrefs.add(f"apo_st{idx:02d}")
        resrefs.add(resref)

    return sorted(resrefs)


def _check_shop_stock_clean():
    """This script copies whatever's CURRENTLY deployed on the dev's live
    game install -- it doesn't regenerate anything itself. If
    _shop_stock.json (extender/area_trampolines/) has any per-seed
    content in it when this runs (leftover from live testing, not
    reset), that content gets baked into the "always-on" trampolines
    this script copies and silently ships to EVERY tester who uses the
    documented setup_game.py path, regardless of their own seed's real
    shop randomization. This is a loud warning, not a silent skip -- the
    operator needs to actually reset (see below) and redeploy before
    re-running this script, not just acknowledge the warning."""
    shop_stock_path = os.path.join(REPO_ROOT, "extender", "area_trampolines", "_shop_stock.json")
    if not os.path.exists(shop_stock_path):
        return
    with open(shop_stock_path, encoding="utf-8") as f:
        stock = json.load(f)
    if any(stock.get(planet) for planet in stock):
        print("=" * 70)
        print("WARNING: _shop_stock.json has real per-seed content in it right now:")
        print(f"  {shop_stock_path}")
        for planet, resrefs in stock.items():
            if resrefs:
                print(f"  {planet}: {len(resrefs)} resrefs")
        print()
        print("Copying now would bake this into the 'always-on' dist/Override")
        print("baseline and ship it to EVERY tester, regardless of their own")
        print("seed's real shop randomization -- this exact bug has shipped")
        print("before. Reset it first:")
        print('  echo {} > "' + shop_stock_path + '"')
        print("  python generate_trampoline_batch.py --all")
        print("  (redeploy the regenerated .ncs files to your live game's Override,")
        print("   e.g. via arm_orchestrator.py --area=<any area you're testing in>,")
        print("   or just copy extender/area_trampolines/*.ncs over yourself)")
        print("then re-run this script.")
        print("=" * 70)
        sys.exit(1)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--game-dir", default=DEFAULT_GAME_DIR,
                         help="Source install to copy already-compiled .ncs files FROM (a dev machine with everything already generated).")
    parser.add_argument("--dist-dir", default=DEFAULT_DIST_DIR,
                         help="Where to write the packaged Override folder (default: repo's dist/Override).")
    args = parser.parse_args()

    _check_shop_stock_clean()

    source_override = os.path.join(args.game_dir, "Override")
    # Files that are edits or copies of the game's own are never shipped: build_game_assets.py makes them on the player's machine.
    import list_game_derived
    # the names do not depend on which install is read; a staging copy that only holds an Override folder falls back to the default install
    names_from = args.game_dir if os.path.isfile(os.path.join(args.game_dir, "chitin.key")) else DEFAULT_GAME_DIR
    built_on_player_machine = list_game_derived.builder_output_names(names_from)
    resrefs = [r for r in collect_expected_resrefs() if f"{r}.ncs".lower() not in built_on_player_machine]
    print(f"Expecting {len(resrefs)} files from {source_override}")

    os.makedirs(args.dist_dir, exist_ok=True)
    copied = 0
    missing = []
    for resref in resrefs:
        src = os.path.join(source_override, f"{resref}.ncs")
        if not os.path.exists(src):
            missing.append(resref)
            continue
        shutil.copy2(src, os.path.join(args.dist_dir, f"{resref}.ncs"))
        copied += 1

    print(f"Copied {copied}/{len(resrefs)} files -> {args.dist_dir}")

    raw_copied = 0
    raw_missing = []
    for fname in EXTRA_RAW_FILES:
        if fname.lower() in built_on_player_machine:
            continue
        src = os.path.join(RAW_OVERRIDE_FILES_DIR, fname)
        if not os.path.exists(src):
            raw_missing.append(fname)
            continue
        shutil.copy2(src, os.path.join(args.dist_dir, fname))
        raw_copied += 1
    print(f"Copied {raw_copied}/{len(EXTRA_RAW_FILES)} raw file(s) -> {args.dist_dir}")

    if missing or raw_missing:
        print(f"\nMISSING {len(missing) + len(raw_missing)} expected file(s) -- source install is out of date, "
              f"re-run the generator scripts (or re-deploy the raw files) against it first:")
        for r in missing:
            print(f"  {r}.ncs")
        for f in raw_missing:
            print(f"  {f}")
        sys.exit(1)


if __name__ == "__main__":
    main()
