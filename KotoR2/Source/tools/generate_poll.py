"""Generates nss/k2se_poll.nss: the game-side poll that reports the state the client turns into location checks.

Reads data/locations.json. Output functions (all report only when a value changed, using the extender's in-memory store):
  PollQuests(oPC)      Q|tag=stage,...     quests past stage 0, in chunks
  PollCharacter(oPC)   L|level  A|alignment  R|slot (recruits)  I|slot=value,... (available companions only)
  PollQuestItems(oPC)  O|tag,...           (list pending: curated quest items)
  PollBazaar(oPC)      B|purchases|exchanges (pending: the Bazaar Jawa)
  PollAll(oPC)         everything above

  python tools/generate_poll.py
"""
import json
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
CHUNK = 10
GOAL_TAGS = ("DefeatDarthNihilus",)


def main():
    data = json.load(open(os.path.join(ROOT, "data", "locations.json"), encoding="utf-8"))
    # GOAL_TAGS: journal quests that goals read although they are not locations (DefeatDarthNihilus 99 = Nihilus defeated)
    quest_tags = sorted({str(l["journal_tag"]) for l in data["locations"] if l["type"] == "quest"} | set(GOAL_TAGS))
    slots = sorted({l["slot"] for l in data["locations"] if l["type"] == "recruit"})
    chunks = [quest_tags[i:i + CHUNK] for i in range(0, len(quest_tags), CHUNK)]
    out = ["// GENERATED by tools/generate_poll.py from data/locations.json. Do not edit by hand.",
           "// Reports the game state that the client turns into location checks. Each report is written only when it changed.",
           '#include "k2se"', "",
           "// writes line to the outbox if the value stored under sKey differs from sValue",
           "void PollReport(string sKey, string sValue, string sLine)",
           "{",
           "    if (K2SE_MemGet(sKey) == sValue) return;",
           "    K2SE_MemSet(sKey, sValue);",
           "    K2SE_OutboxPut(sLine);",
           "}", ""]
    for n, tags in enumerate(chunks):
        out.append("string PollQuestChunk%d()" % n)
        out.append("{")
        out.append('    string s = "";')
        out.append("    int n;")
        for t in tags:
            out.append('    n = GetJournalEntry("%s"); if (n > 0) s = s + "%s=" + IntToString(n) + ",";' % (t, t))
        out.append("    return s;")
        out.append("}")
        out.append("")
    out.append("void PollQuests(object oPC)")
    out.append("{")
    out.append("    string s;")
    for n in range(len(chunks)):
        out.append("    s = PollQuestChunk%d(); if (s != \"\") PollReport(\"pq%d\", s, \"Q|\" + GetStringLeft(s, GetStringLength(s) - 1));" % (n, n))
    out.append("}")
    out.append("")
    out.append("void PollCharacter(object oPC)")
    out.append("{")
    out.append('    int nLevel = GetHitDice(oPC);')
    out.append('    if (nLevel < 1) return;            // the creature is not loaded yet: GetGoodEvilValue below would crash the game on it')
    out.append('    PollReport("pl", IntToString(nLevel), "L|" + IntToString(nLevel));')
    out.append('    PollReport("px", IntToString(GetXP(oPC)), "XP|" + IntToString(GetXP(oPC)));')
    out.append('    int nAlign = GetGoodEvilValue(oPC);')
    out.append('    PollReport("pa", IntToString(nAlign), "A|" + IntToString(nAlign));')
    out.append('    string sInf = "";')
    for slot in slots:
        out.append('    if (IsAvailableCreature(%d)) { PollReport("pr%d", "1", "R|%d"); sInf = sInf + "%d=" + IntToString(GetInfluence(%d)) + ","; }' % (slot, slot, slot, slot, slot))
    out.append('    if (sInf != "") PollReport("pi", sInf, "I|" + GetStringLeft(sInf, GetStringLength(sInf) - 1));')
    out.append("}")
    out.append("")
    tags = ["Atton", "BaoDur", "Mand", "G0T0", "Handmaiden", "HK47", "Kreia", "Mira", "T3M4", "VisasMarr", "Hanharr", "Disciple"]
    out.append("// Class report of the companions in the party: CC|slot:class1:level1:class2:level2,... (only when it changes). The client compares it with the seed's")
    out.append("// plan (client/k2_companions.py) and orders the class rebuild where they differ.")
    out.append("void PollCompanions(object oPC)")
    out.append("{")
    out.append('    string s = "";')
    for i, t in enumerate(tags):
        out.append('    if (IsNPCPartyMember(%d)) { object o%d = GetObjectByTag("%s"); if (GetIsObjectValid(o%d)) s = s + "%d:" + IntToString(GetClassByPosition(1, o%d)) + ":" + '
                   'IntToString(GetLevelByPosition(1, o%d)) + ":" + IntToString(GetClassByPosition(2, o%d)) + ":" + IntToString(GetLevelByPosition(2, o%d)) + ","; }' % (i, i, t, i, i, i, i, i, i))
    out.append("    int nX;")
    out.append("    for (nX = 12; nX < 32; nX++)")
    out.append("    {")
    out.append("        if (!IsNPCPartyMember(nX)) continue;")
    out.append('        object oX = GetObjectByTag("apxc" + IntToString(nX));')
    out.append("        if (!GetIsObjectValid(oX)) continue;")
    out.append('        s = s + IntToString(nX) + ":" + IntToString(GetClassByPosition(1, oX)) + ":" + IntToString(GetLevelByPosition(1, oX)) + ":" + '
               'IntToString(GetClassByPosition(2, oX)) + ":" + IntToString(GetLevelByPosition(2, oX)) + ",";')
    out.append("    }")
    out.append('    string t = "";')
    out.append('    if (s != "") t = GetStringLeft(s, GetStringLength(s) - 1);')
    out.append('    PollReport("pcc", s, "CC|" + t);')
    out.append("}")
    out.append("")
    out.append("// DeathLink: the player's death is reported once. A death the dispatcher caused (a received DeathLink) is flagged in dl_incoming and not reported;")
    out.append("// the flag is given one poll of grace and then dropped, so an immune player does not swallow a later real death.")
    out.append("void PollDeath(object oPC)")
    out.append("{")
    out.append("    if (GetIsDead(oPC))")
    out.append("    {")
    out.append('        if (K2SE_MemGet("pdead") == "1") return;')
    out.append('        K2SE_MemSet("pdead", "1");')
    out.append('        if (K2SE_MemGet("dl_incoming") == "1") { K2SE_MemSet("dl_incoming", "0"); return; }')
    out.append('        K2SE_OutboxPut("DL|death");')
    out.append("        return;")
    out.append("    }")
    out.append('    K2SE_MemSet("pdead", "0");')
    out.append('    if (K2SE_MemGet("dl_incoming") == "2") K2SE_MemSet("dl_incoming", "0");')
    out.append('    else if (K2SE_MemGet("dl_incoming") == "1") K2SE_MemSet("dl_incoming", "2");')
    out.append("}")
    out.append("")
    qtags = sorted({l["tag"] for l in data["locations"] if l["type"] == "questitem"})
    out.append("// quest items: the tags of the listed items the player holds right now (the client treats each tag it sees as a check)")
    out.append("void PollQuestItems(object oPC)")
    out.append("{")
    out.append('    string s = "";')
    for t in qtags:
        out.append('    if (GetIsObjectValid(GetItemPossessedBy(oPC, "%s"))) s = s + "%s,";' % (t, t))
    out.append('    if (s != "") PollReport("po", s, "O|" + GetStringLeft(s, GetStringLength(s) - 1));')
    out.append("}")
    out.append("")
    out.append("// Item log for building the quest-item list from play: with ap_item_log=1 in config.txt, the plot-flagged items the player holds are reported as")
    out.append("// IT|tag~name,tag~name (only when the set changes). The client keeps a csv of what it sees (client/KotorTwoClient.py, tools/item_log_report.py).")
    out.append("void PollItemLog(object oPC)")
    out.append("{")
    out.append('    if (K2SE_ConfigInt("ap_item_log", 0) == 0) return;')
    out.append('    string s = "";')
    out.append("    object oItem = GetFirstItemInInventory(oPC);")
    out.append("    while (GetIsObjectValid(oItem))")
    out.append("    {")
    out.append('        if (GetPlotFlag(oItem)) s = s + GetTag(oItem) + "~" + GetName(oItem) + ",";')
    out.append("        oItem = GetNextItemInInventory(oPC);")
    out.append("    }")
    out.append('    string t = "";')
    out.append('    if (s != "") t = GetStringLeft(s, GetStringLength(s) - 1);')
    out.append('    PollReport("pit", s, "IT|" + t);')
    out.append("}")
    out.append("")
    out.append("// the Bazaar: B|<purchases>|<token exchanges>, the number of receipt items the player holds (a deal gives one receipt; nss/k2ap_bazaar.nss)")
    out.append("void PollBazaar(object oPC)")
    out.append("{")
    out.append("    int nBuy = 0;")
    out.append("    int nSwap = 0;")
    out.append("    object oItem = GetFirstItemInInventory(oPC);")
    out.append("    while (GetIsObjectValid(oItem))")
    out.append("    {")
    out.append('        if (GetTag(oItem) == "ap_bz_buy") nBuy += GetItemStackSize(oItem);')
    out.append('        else if (GetTag(oItem) == "ap_bz_swap") nSwap += GetItemStackSize(oItem);')
    out.append("        oItem = GetNextItemInInventory(oPC);")
    out.append("    }")
    out.append('    if (nBuy + nSwap > 0) PollReport("pbz", IntToString(nBuy) + "," + IntToString(nSwap), "B|" + IntToString(nBuy) + "|" + IntToString(nSwap));')
    out.append("}")
    out.append("")
    out.append("void PollAll(object oPC)")
    out.append("{")
    out.append("    PollQuests(oPC);")
    out.append("    PollCharacter(oPC);")
    out.append("    PollDeath(oPC);")
    out.append("    PollCompanions(oPC);")
    out.append("    PollQuestItems(oPC);")
    out.append("    PollItemLog(oPC);")
    out.append("    PollBazaar(oPC);")
    out.append("}")
    path = os.path.join(ROOT, "nss", "k2se_poll.nss")
    with open(path, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote %s: %d quest tags in %d chunks, %d companion slots" % (path, len(quest_tags), len(chunks), len(slots)))


main()
