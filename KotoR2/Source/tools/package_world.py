"""Builds dist/kotor2.apworld and refreshes the full YAML template (yaml/KotOR 2 TSL.yaml) from the world's options.

The world is synced into the scratch core (ap_core) first, so the template is generated by the real options code. No minimum Archipelago version is pinned
in the package (pin it only for a known install). Usage: python tools/package_world.py
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
CORE = os.path.join(ROOT, "ap_core")
SRC = os.path.join(ROOT, "worlds", "kotor2")
DST = os.path.join(CORE, "worlds", "kotor2")
WORLD_VERSION = "0.0.2"
# The Archipelago version the players run (the KotOR 1 players use 0.6.7; newer versions should work). The scratch core here is 0.6.8, so the generated
# template is rewritten to ask for this one. Not tested against a 0.6.7 core (none is available here).
REQUIRED_AP = "0.6.7"


def sync() -> None:
    os.makedirs(os.path.join(SRC, "data"), exist_ok=True)
    for name in ("gates.json", "locations.json", "extra_companions.json", "shops.json", "shop_pool.json", "enemies.json", "doors.json", "crafting.json", "peragus.json"):
        shutil.copy(os.path.join(ROOT, "data", name), os.path.join(SRC, "data", name))
    if os.path.isdir(DST):
        shutil.rmtree(DST)
    shutil.copytree(SRC, DST, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "test"))


def package() -> str:
    os.makedirs(os.path.join(ROOT, "dist"), exist_ok=True)
    out = os.path.join(ROOT, "dist", "kotor2.apworld")
    meta = {"game": "KotOR 2 TSL", "world_version": WORLD_VERSION, "version": 7, "compatible_version": 7}
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for base, dirs, files in os.walk(SRC):
            dirs[:] = [d for d in dirs if d not in ("__pycache__", "test")]
            for f in files:
                if f.endswith(".pyc"):
                    continue
                path = os.path.join(base, f)
                z.write(path, os.path.join("kotor2", os.path.relpath(path, SRC)))
        z.writestr("kotor2/archipelago.json", json.dumps(meta, indent=2))
    return out


def template() -> str:
    tmp = tempfile.mkdtemp()
    code = ("import Options, sys; Options.generate_yaml_templates(sys.argv[1], False)")
    subprocess.check_call([sys.executable, "-c", code, tmp], cwd=CORE)
    produced = os.path.join(tmp, "KotOR 2 TSL.yaml")
    target = os.path.join(ROOT, "yaml", "KotOR 2 TSL.yaml")
    with open(produced, encoding="utf-8") as f:
        text = f.read()
    text, n = re.subn(r"(?m)^(\s*version:\s*)\d+\.\d+\.\d+", lambda m: m.group(1) + REQUIRED_AP, text, count=1)
    if n != 1:
        raise SystemExit("template has no version line to pin")
    with open(target, "w", encoding="utf-8") as f:
        f.write(text)
    shutil.rmtree(tmp, ignore_errors=True)
    return target


if __name__ == "__main__":
    sync()
    print(package())
    print(template())
