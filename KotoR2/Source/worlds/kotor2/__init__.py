class KotorTwoWorld(World):
    """Knights of the Old Republic II: items and checks randomised across the Exile's journey, with story gates held until enough progression items arrive."""
    game = "KotOR 2 TSL"
    web = KotorTwoWebWorld()
    options_dataclass = KotorTwoOptions
    options: KotorTwoOptions
    item_name_to_id = ITEM_NAME_TO_ID
    location_name_to_id = LOCATION_NAME_TO_ID
    topology_present = False

    level_cap: int = 20
    door_pairs: typing.List[typing.Tuple[str, str]] = []          # area_randomizer: the new coupled pairs of doors (keys of data/doors.json)
    door_path_reqs: typing.Dict[str, typing.Dict[str, int]] = {}  # area_randomizer: per module, what reaching it through the new pairs needs (family key -> tokens)
    guaranteed_xp_items: int = 0
    bounty_carriers: typing.List[typing.Tuple[str, int]] = []     # bounty_cards: (module, index of the spawn point) of each creature that carries a datapad, easiest area first

    # ---- options in plain form ------------------------------------------------------------------------------------------
    def _gates_active(self) -> bool:
        return bool(self.options.story_gates)

    def _disabled(self) -> typing.Set[str]:
        return set(self.options.disabled_gates.value)

    def _counts(self) -> typing.Dict[str, int]:
        return token_counts(self._disabled()) if self._gates_active() else {}

    def _goal_counts(self) -> typing.Dict[str, int]:
        """Tokens the chosen goal needs: all of them, except that the Nihilus goal ends before the Kreia fight gate."""
        if not self._gates_active():
            return {}
        if self.options.goal.value == GOAL_NIHILUS:
            return goal_token_counts(self._disabled(), ("FIN4",))
        return self._counts()

    def _ap_companion_count(self) -> int:
        """Generated companions: the option, but the extra party slots (12 to 31, twenty) are shared with the chosen named extras."""
        return max(0, min(self.options.ap_companions.value, 20 - len(self.options.extra_companions.value)))

    def _offered_companions(self) -> typing.List[str]:
        """Companion items the seed offers, in unlock order: the twelve base companions, the chosen extras, then the generated ones."""
        mode = self.options.companions.value
        if mode not in (COMPANIONS_AP_GATED, COMPANIONS_AP_LIMITED):
            return []
        names = list(BASE_COMPANION_ITEMS)
        names += [EXTRA_COMPANION_ITEMS[c] for c in sorted(self.options.extra_companions.value)]
        names += ["AP Companion"] * self._ap_companion_count()
        return names

    def _companion_pool_names(self) -> typing.List[str]:
        """The offered companions that are items in the pool: only in ap_gated (in ap_limited the client unlocks them by progress)."""
        return self._offered_companions() if self.options.companions.value == COMPANIONS_AP_GATED else []

    def _trap_names(self) -> typing.List[str]:
        return [TRAP_BY_KEY[k] for k in sorted(self.options.trap_types.value) if k in TRAP_BY_KEY]

    def _location_used(self, loc) -> bool:
        if loc.only_if_option == "companions != none" and self.options.companions.value == COMPANIONS_NONE:
            return False
        if loc.type == "level" and loc.spec["level"] > self.level_cap:
            return False
        if loc.type == "bazaar" and not self.options.bazaar:
            return False
        if loc.type == "bounty" and loc.spec["count"] > len(self.bounty_carriers):
            return False
        if loc.type == "questextra" and loc.spec["part"] > self.options.additional_quest_checks.value:
            return False
        if loc.type == "area" and not self.options.area_visit_checks:
            return False
        if loc.type == "alignment" and not self.options.alignment_checks:
            return False
        if self.options.shortened_peragus and loc.name in self._peragus_removed():
            return False
        return True

    def _peragus_removed(self) -> typing.FrozenSet[str]:
        """shortened_peragus used to remove the checks the condensed opening cannot produce (the data file still lists them in removed_locations). None is removed any more:
        the client gives out every Peragus check (areas, its own quests, the Atton, Kreia and T3-M4 recruits) when the player leaves Peragus (client/k2_tracker.py)."""
        return frozenset()

    # ---- generation ------------------------------------------------------------------------------------------------------------
    def generate_early(self) -> None:
        o = self.options
        self.door_pairs, self.door_path_reqs = [], {}
        if o.area_randomizer.value:
            data = door_data()
            try:
                self.door_pairs = shuffle_doors(data, self.random)
            except ShuffleError as e:
                raise OptionError("KotOR 2 TSL: the area randomizer could not build a connected set of doors (%s)." % e)
            self.door_path_reqs = path_requirements(self.door_pairs, data)
        self.bounty_carriers = self._pick_bounty_carriers() if (o.enemy_randomizer.value and o.bounty_cards.value) else []
        goal = o.goal.value
        self.level_cap = max(o.level_target.value, o.goal_level.value if goal == GOAL_HIGH_LEVEL else 0)
        if goal in (GOAL_INFLUENCE, GOAL_CULT) and o.companions.value == COMPANIONS_NONE:
            raise OptionError("KotOR 2 TSL: the goal %s needs companions (companions: none removes the recruit and influence checks)." %
                              o.goal.current_option_name)
        if goal == GOAL_CULT and o.companions.value == COMPANIONS_AP_LIMITED:
            offered = len(self._offered_companions())
            if offered * o.companion_unlock_step.value > 100:
                raise OptionError("KotOR 2 TSL: with companion_unlock_step %d the %d offered companions are not all unlocked by 100 percent of "
                                  "your checks, so cult_leader could not be reached." % (o.companion_unlock_step.value, offered))
        if goal == GOAL_HIGH_LEVEL:
            self._check_level_supply(o.goal_level.value)

    def _check_level_supply(self, level: int) -> None:
        o = self.options
        needed = xp_for_level(level)
        checks = sum(1 for l in LOCATIONS if self._location_used(l))
        if o.experience_mode.value == MODE_LIMITED:
            if checks * o.experience_limiter.value < needed:
                raise OptionError("KotOR 2 TSL: goal level %d needs %d XP but %d checks x experience_limiter %d only give %d. Raise the limiter or "
                                  "use fewer check families removed." % (level, needed, checks, o.experience_limiter.value,
                                                                          checks * o.experience_limiter.value))
        elif o.experience_mode.value == MODE_GATED:
            self.guaranteed_xp_items = math.ceil(needed / o.experience_item.value)
        elif level > 20:
            logging.warning("KotOR 2 TSL (%s): goal level %d relies on vanilla XP, which gives roughly level 20 to 25; consider experience_mode "
                            "ap_limited or ap_gated.", self.player_name, level)

    def create_item(self, name: str) -> KotorTwoItem:
        data = ITEMS[name]
        classification = data.classification
        if self.options.goal.value == GOAL_CULT and name.startswith(("Companion: ", "AP Companion")):
            classification = ItemClassification.progression    # the goal counts them, and only progression items count in logic
        return KotorTwoItem(name, classification, data.id, self.player)

    def _goal_rule(self, locations_by_name: typing.Dict[str, Location]) -> typing.Optional[typing.Callable]:
        o = self.options
        goal = o.goal.value
        player = self.player
        if goal in (GOAL_DEFEAT_KREIA, GOAL_NIHILUS):
            final = tuple(self._goal_counts().items())
            if not final:
                return None
            return lambda state: all(state.count(fam, player) >= n for fam, n in final)
        if goal == GOAL_HIGH_LEVEL:
            level_loc = locations_by_name["Level %d" % o.goal_level.value]
            return lambda state: level_loc.can_reach(state)
        if goal == GOAL_INFLUENCE:
            infl = [l for n, l in locations_by_name.items() if n.startswith("Influence: ")]
            need = min(o.influence_goal_count.value, len(infl))
            return lambda state: sum(1 for l in infl if l.can_reach(state)) >= need
        recruits = [l for n, l in locations_by_name.items() if n.startswith("Companion Recruited: ")]
        items = tuple((n, self._companion_pool_names().count(n)) for n in dict.fromkeys(self._companion_pool_names())) \
            if o.companions.value == COMPANIONS_AP_GATED else ()
        return lambda state: all(l.can_reach(state) for l in recruits) and all(state.count(n, player) >= c for n, c in items)

    def _spare_progression_ids(self) -> typing.Set[int]:
        """Locations that join the progression-capable ones when the safe ones (the quests the story forces, area visits, recruits outside an exclusive pair; see
        tools/build_world_data.py) are too few for the tokens, which happens when the area-visit checks are off: missable quests, never the companion-dependent ones, in the
        order of the data file, enough to hold every token with a margin."""
        used = [loc for loc in LOCATIONS if self._location_used(loc)]
        capable = sum(1 for loc in used if loc.progression)
        short = sum(self._counts().values()) + PROGRESSION_MARGIN - capable
        if short <= 0:
            return set()
        spare = [loc.id for loc in used if not loc.progression and loc.type == "quest" and not loc.spec.get("companion_dependent")][:short]
        logging.warning("KotOR 2 TSL (%s): too few locations that are safe for progression items (%d, tokens %d): %d missable quests may hold them too; turn the area-visit checks on to avoid this",
                        self.player_name, capable, sum(self._counts().values()), len(spare))
        return set(spare)

    def create_regions(self) -> None:
        spare_ids = self._spare_progression_ids()
        menu = Region("Menu", self.player, self.multiworld)
        world = Region("Galaxy", self.player, self.multiworld)
        self.multiworld.regions += [menu, world]
        menu.connect(world)
        counts = self._counts()
        by_name: typing.Dict[str, Location] = {}
        for loc in LOCATIONS:
            if not self._location_used(loc):
                continue
            location = KotorTwoLocation(self.player, loc.name, loc.id, world)
            if not loc.progression and loc.id not in spare_ids:
                location.item_rule = lambda item: not item.advancement
            needs = dict(loc.requires)
            if loc.type == "bounty":
                needs = self._bounty_requirements(loc.spec["count"])
            for fam, n in self._door_requirements(loc).items():       # area_randomizer: the way to the location's module is part of its logic
                needs[fam] = max(needs.get(fam, 0), n)
            reqs = [(fam, min(n, counts.get(fam, 0))) for fam, n in needs.items() if counts.get(fam, 0) > 0]
            if reqs:
                player = self.player
                location.access_rule = lambda state, reqs=tuple(reqs), p=player: all(state.count(fam, p) >= n for fam, n in reqs)
            world.locations.append(location)
            by_name[loc.name] = location
        victory = KotorTwoLocation(self.player, GOAL_EVENT_NAMES[self.options.goal.value], None, world)
        victory.place_locked_item(KotorTwoItem("Victory", ItemClassification.progression, None, self.player))
        rule = self._goal_rule(by_name)
        if rule:
            victory.access_rule = rule
        world.locations.append(victory)

    def _door_requirements(self, loc) -> typing.Dict[str, int]:
        """area_randomizer: the tokens needed to walk to the module(s) of a location through the shuffled doors, {item name: count}. A location in several modules
        takes the largest need among them; if one of them is outside the pool (so reachable as in the base game) it takes none."""
        if not self.door_path_reqs:
            return {}
        modules = [m for m in (loc.spec.get("module") or loc.spec.get("modules") or "").split(";") if m]
        if not modules or any(m not in self.door_path_reqs for m in modules):
            return {}
        merged: typing.Dict[str, int] = {}
        for m in modules:
            for key, n in self.door_path_reqs[m].items():
                merged[FAMILY_KEYS[key]] = max(merged.get(FAMILY_KEYS[key], 0), n)
        return merged

    def _door_plan(self) -> typing.Dict[str, typing.Any]:
        """area_randomizer: what the client rewrites in the game. {"links": [{door, module, list, index, kind, to_module, to_waypoint}]}: every pooled door now leads
        to the module of its new partner and arrives at the waypoint next to the partner. Empty when the option is off."""
        if not self.door_pairs:
            return {}
        doors = door_data()["doors"]
        links = []
        for a, b in self.door_pairs:
            for here, there in ((a, b), (b, a)):
                d = doors[here]
                links.append({"door": here, "module": d["module"], "list": d["list"], "index": d["index"], "kind": d["kind"],
                              "to_module": doors[there]["module"], "to_waypoint": doors[there]["arrive"]})
        return {"links": sorted(links, key=lambda l: l["door"])}

    def _start_stats(self) -> typing.Optional[typing.List[int]]:
        """starting_stats random: 14 values from 1 to 20, the six abilities (Strength, Dexterity, Constitution, Intelligence, Wisdom, Charisma) and then the
        eight skills (Computer Use, Demolitions, Stealth, Awareness, Persuade, Repair, Security, Treat Injury), set when the game starts."""
        if self.options.starting_stats.value != STATS_RANDOM:
            return None
        return [self.random.randint(1, 20) for _ in range(14)]

    def create_items(self) -> None:
        o = self.options
        pool: typing.List[KotorTwoItem] = []
        for name, n in self._counts().items():
            pool += [self.create_item(name) for _ in range(n)]
        pool += [self.create_item(n) for n in self._companion_pool_names()]
        if o.companions.value != COMPANIONS_NONE:                                    # the Party Console (opens the party screen): in every seed that has companions
            pool.append(self.create_item("Party Console"))
        if o.starting_class.value == STARTING_PRESTIGE_GATED:
            pool.append(self.create_item("Prestige Class"))
        if o.multiclass_companion.value == MULTICLASS_PRESTIGE and o.companions.value != COMPANIONS_NONE:
            pool += [self.create_item("Companion Prestige: " + COMPANION_NAMES[slot]) for slot in JEDI_CAPABLE_SLOTS]
        pool += [self.create_item("Experience Points") for _ in range(self.guaranteed_xp_items)]
        if o.crafting_gated.value:
            pool += [self.create_item(CRAFT_ITEM_BY_TYPE[t]) for t in self._craft_types()]
        if o.archipelago_vendor.value:
            pool += [self.create_item(VENDOR_PASS_ITEM_BY_KEY[k]) for k in self._vendor_passes()]
        slots = sum(1 for l in self.multiworld.get_unfilled_locations(self.player))
        if len(pool) > slots:
            raise OptionError("KotOR 2 TSL: %d items must be in the pool but only %d locations exist; raise level_target, turn on more check "
                              "families, or offer fewer companions." % (len(pool), slots))
        names = [n for n in FILLER_WEIGHTS
                 if not (n == "Experience Points" and o.experience_mode.value != MODE_GATED)
                 and not (n == "Republic Credits" and o.credit_mode.value != MODE_GATED)]
        if not names:
            names = ["Skill: Computer Use"]
        weights = [FILLER_WEIGHTS.get(n, 1) for n in names]
        traps = self._trap_names()
        gear_order: typing.List[str] = []
        for _ in range(slots - len(pool)):
            if traps and self.random.random() * 100 < o.trap_percentage.value:
                pool.append(self.create_item(self.random.choice(traps)))
            elif o.gear_items.value and self.random.random() * 100 < o.gear_items.value:
                if not gear_order:                                          # every piece once, in a random order, before any repeats
                    gear_order = list(GEAR_ITEM_NAMES)
                    self.random.shuffle(gear_order)
                pool.append(self.create_item(gear_order.pop()))
            else:
                pool.append(self.create_item(self.random.choices(names, weights)[0]))
        self.multiworld.itempool += pool

    def set_rules(self) -> None:
        self.multiworld.completion_condition[self.player] = lambda state: state.has("Victory", self.player)

    def get_filler_item_name(self) -> str:
        return "Republic Credits"

    def _goal_spec(self) -> typing.Dict[str, typing.Any]:
        o = self.options
        goal = o.goal.value
        if goal == GOAL_NIHILUS:
            return {"type": "nihilus"}
        if goal == GOAL_HIGH_LEVEL:
            return {"type": "level", "level": o.goal_level.value}
        if goal == GOAL_INFLUENCE:
            return {"type": "influence", "count": o.influence_goal_count.value}
        if goal == GOAL_CULT:
            return {"type": "cult", "items": self._companion_pool_names()}
        return {"type": "kreia"}

    def _start_class(self) -> typing.Optional[typing.Dict[str, int]]:
        """The class the player is converted to at the start of the run, decided here so the seed is reproducible. Class ids are the game's classes.2da rows:
        0 Soldier, 1 Scout, 2 Scoundrel, 3 Jedi Guardian, 4 Jedi Consular, 5 Jedi Sentinel, 6 Combat Droid, 7 Expert Droid, 9 Tech Specialist, 10 Battle Droid (the game's cut row), 11 Weapon Master
        (Vanguard), 12 Master (Sage), 13 Watchman (Shadow), 14 Sith Marauder, 15 Sith Lord (Sorcerer), 16 Sith Assassin. mode 1 strips the Jedi feats and powers
        (the new class cannot have them); race 5 makes the player a droid (the appearance is not changed: a player model change is not safe)."""
        value = self.options.starting_class.value
        if value == STARTING_DROID:                                  # the player is always the Battle Droid; the companions' droid classes are drawn (companion_class: droid)
            return {"class": BATTLE_DROID, "mode": 1, "race": 5, "look": self.random.choice(PLAYER_BATTLE_LOOKS)}
        if value == 1:
            cls = self.random.choice([0, 1, 2])
        elif value == 2:
            cls = self.random.choice([0, 1, 2, 3, 4, 5])
        elif value == 3:
            cls = self.random.choice([11, 12, 13, 14, 15, 16])
        else:
            return None
        return {"class": cls, "mode": 1 if cls in (0, 1, 2) else 0}

    def _prestige_pair(self) -> typing.Optional[typing.List[int]]:
        """[light class, dark class] of the prestige pair chosen for prestige_gated; the grant takes the side from the player's alignment when the item arrives
        (a neutral player gets a random side). Pairs: Vanguard 11 / Marauder 14, Shadow 13 / Assassin 16, Sage 12 / Sorcerer 15."""
        if self.options.starting_class.value != STARTING_PRESTIGE_GATED:
            return None
        return list(self.random.choice([(11, 14), (13, 16), (12, 15)]))

    def _companion_classes(self) -> typing.Dict[str, typing.Dict[str, int]]:
        """Class changes per companion slot for the companion_class option, decided here. Slots: 0 Atton, 1 Bao-Dur, 2 Mandalore, 3 G0-T0, 4 Handmaiden, 5 HK-47,
        6 Kreia, 7 Mira, 8 T3-M4, 9 Visas, 10 Hanharr, 11 Disciple. The three droids (3, 5, 8) are never changed: they are droids already. The level is not
        decided here: the game raises each companion to the player's level when it is delivered. A companion who is not in the result keeps their own class."""
        value = self.options.companion_class.value
        jedi_slots, droid_slots = (6, 9), (3, 5, 8)
        out: typing.Dict[str, typing.Dict[str, int]] = {}
        for slot in range(12):
            if slot in droid_slots:
                continue
            if value == COMPANION_CLASS_JEDI and slot not in jedi_slots:
                out[str(slot)] = {"class": self.random.choice([3, 4, 5]), "mode": 0}
            elif value == COMPANION_CLASS_NO_JEDI and slot in jedi_slots:
                out[str(slot)] = {"class": self.random.choice([0, 1, 2, 9]), "mode": 1}
            elif value == COMPANION_CLASS_DROID:
                cls = self.random.choice(DROID_CLASSES)
                out[str(slot)] = {"class": cls, "mode": 1, "race": 5, "look": self.random.choice(DROID_LOOK[cls]), "look_method": "disguise" if slot in DISGUISE_SLOTS else "template"}
            elif value == COMPANION_CLASS_RANDOM_BASE:
                cls = self.random.choice([0, 1, 2, 3, 4, 5, 9])
                out[str(slot)] = {"class": cls, "mode": 1 if cls in (0, 1, 2, 9) else 0}
        return out

    def _extras_plan(self) -> typing.List[typing.Dict[str, typing.Any]]:
        """The extra companions in slot order, from slot 12: the chosen K1 and K2 characters in the order of data/extra_companions.json, then the generated ones.
        Every entry carries what the game needs to build the creature (look, portrait, sex, base class, how the look is applied) and the name of its item; all of them are
        built from the one generic base template (data/extra_companions.json). A generated companion is named after a player of this multiworld (other players first, then
        yourself, round and round; a name used again is numbered: "Name 2"), with a look from the pool, a portrait of its sex and a random base class."""
        if self.options.companions.value not in (COMPANIONS_AP_GATED, COMPANIONS_AP_LIMITED):
            return []
        data = extra_companion_data()
        chosen = self.options.extra_companions.value
        method = data["look_method"]
        out: typing.List[typing.Dict[str, typing.Any]] = []
        for entry in data["extras"]:
            if entry["name"] in chosen:
                out.append(dict(entry, slot=12 + len(out), item="Companion: " + entry["name"], look_method=method))
        others = [self.multiworld.player_name[p] for p in sorted(self.multiworld.player_ids) if p != self.player] or []
        names = others + [self.player_name]
        # the generated companions take different looks from the pool (none of the story companions' looks); more companions than looks start the pool again
        looks: typing.List[dict] = []
        for k in range(self._ap_companion_count()):
            if not looks:
                looks = list(data["ap_looks"])
                self.random.shuffle(looks)
            look = looks.pop()
            portrait = self.random.choice(data["portraits"]["female" if look["gender"] else "male"])
            base = names[k % len(names)][:20]
            turn = k // len(names)                                   # the second companion named after the same player is "Name 2", and so on
            out.append({"name": base if turn == 0 else "%s %d" % (base, turn + 1), "kind": "ap", "appearance": look["appearance"], "portrait": portrait, "gender": look["gender"],
                        "class": self.random.choice(data["ap_classes"]), "fallback_appearance": look["appearance"], "fallback_portrait": portrait,
                        "slot": 12 + len(out), "item": "AP Companion", "look_method": method})
        return out

    def _shop_plan(self) -> typing.Dict[str, typing.Any]:
        """shop_randomizer: what the client does to the game's stores. Each planet draws shop_count items from the pool with this player's random generator (so the
        planets differ) and every randomized store of the planet sells that list, plus the staples (medpacs, repair kits, spikes) that no pool draw would leave in.
        {"stores": [{module, utm, tag, stock}], "silence": [the game's own stock scripts], "supplies_only"}; empty when neither shop_randomizer nor crafting_gated is on.
        The Pazaak dealers are not in it. With crafting_gated every store sells only crafting supplies, Components and Chemicals (SHOP_SUPPLY_STOCK: priced copies of the
        game's two items, made by client/k2_shop.py), whether or not the shops are randomized: gear comes from the crafting types the items unlock, not from the shelves."""
        supplies = bool(self.options.crafting_gated.value)
        if not self.options.shop_randomizer.value and not supplies:
            return {}
        data = shop_data()
        if supplies:
            stock = {planet: list(SHOP_SUPPLY_STOCK) for planet in data["planets"]}
        else:
            count = min(self.options.shop_count.value, len(data["pool"]))
            stock = {planet: list(data["staples"]) + self.random.sample(data["pool"], count) for planet in data["planets"]}
        stores = [{"module": s["module"], "utm": s["utm"], "tag": s["tag"], "stock": stock[s["planet"]]} for s in data["stores"] if not s["leave_alone"]]
        return {"stores": stores, "silence": list(data["stock_scripts"]), "supplies_only": supplies}

    def _peragus_plan(self) -> typing.Dict[str, typing.Any]:
        """shortened_peragus: what the client does to the opening, from data/peragus.json (variant A, "short hallway", of docs/PERAGUS_CONDENSED.md).
        {"variant", "decisions", "skipped_modules", "removed_locations", "hooks": [{id, module, replaces, run, ops}]}. A hook's optional operations are
        added when the matching decision is on, and a hook with a "when" is kept only when its decision holds. Empty when the option is off. The decisions
        (data/peragus.json "decisions") are the defaults of the research until the user settles them; the game side is not built, so nothing runs yet."""
        if not self.options.shortened_peragus.value:
            return {}
        data = peragus_data()
        decisions = dict(data["decisions"])
        hooks = []
        for hook in data["hooks"]:
            when = hook.get("when")
            if when:
                key, _, want = (p.strip() for p in when.partition("=="))
                if str(decisions.get(key)) != want:
                    continue
            ops = list(hook["ops"])
            for name, extra in hook.get("optional", {}).items():
                if decisions.get(name):
                    at = len(ops) - 1 if ops and ops[-1]["op"] == "load" else len(ops)      # a module change always stays last
                    ops[at:at] = extra
            hooks.append({"id": hook["id"], "module": hook["module"], "replaces": hook["replaces"], "run": hook["run"], "ops": ops})
        if decisions["xp"] == "journal":
            hooks.append({"id": "xp", "module": "101PER", "replaces": "a_106perjump", "run": "with the jump", "ops": list(data["xp_grants"]["journal"])})
        return {"variant": data["variant"], "decisions": decisions, "skipped_modules": list(data["skipped_modules"]),
                "removed_locations": sorted(self._peragus_removed()), "hooks": hooks}

    def _vendor_passes(self) -> typing.List[str]:
        """The Vendor's menus this seed has: skill, ability and alignment training, and the crafting supplies only with a crafting mode."""
        return ["skill", "abil", "align"] + (["supply"] if self.options.crafting_mode.value else [])

    def _craft_types(self) -> typing.List[str]:
        """The crafting types this seed has: the workbench's gear tabs only when crafting_mode adds gear recipes, and always the vanilla upgrade parts and the lab."""
        types = list(GEAR_CRAFT_TYPES) if self.options.crafting_mode.value else []
        return types + ["parts", "lab"]

    def _crafting_plan(self) -> typing.Dict[str, typing.Any]:
        """crafting_mode / crafting_gated: what the client builds. {"mode", "seed", "gated", "types", "gear": [[resref, type]]}. With crafting_mode off and no gating
        the game's crafting is untouched and the plan is empty. The ranks and costs are worked out by the client from the game's own templates (seeded by "seed")."""
        mode, gated = self.options.crafting_mode.value, bool(self.options.crafting_gated.value)
        if not mode and not gated:
            return {}
        return {"mode": mode, "seed": self.random.getrandbits(32), "gated": gated, "types": self._craft_types(),
                "gear": crafting_data()["gear"] if mode else [], "gear_gated": bool(mode and self.options.gear_items.value)}

    def _module_needs(self, module: str) -> typing.Dict[str, int]:
        """The tokens it takes to be in a module: its area location's requirement, plus (area_randomizer) the way there through the shuffled doors, {item name: count}."""
        for loc in LOCATIONS:
            if loc.type == "area" and loc.spec.get("module") == module:
                needs = dict(loc.requires)
                for fam, n in self._door_requirements(loc).items():
                    needs[fam] = max(needs.get(fam, 0), n)
                return needs
        return {}

    def _pick_bounty_carriers(self) -> typing.List[typing.Tuple[str, int]]:
        """bounty_cards: which spawn points carry a Bounty Datapad. Round by round, each eligible area gives one more point (in a random order of areas and points) until
        BOUNTY_TOTAL are chosen, so every area carries two to four. Returned easiest area first (fewest tokens needed to get there), which is the order the checks'
        logic uses: Bounty Datapad #n needs the n easiest carriers' areas."""
        modules = enemy_data()["modules"]
        areas = sorted(m for m in BOUNTY_MODULES if m in modules)
        spare = {m: list(range(len(modules[m]["points"]))) for m in areas}
        for m in areas:
            self.random.shuffle(spare[m])
        chosen: typing.List[typing.Tuple[str, int]] = []
        while len(chosen) < BOUNTY_TOTAL and any(spare.values()):
            order = list(areas)
            self.random.shuffle(order)
            for m in order:
                if len(chosen) < BOUNTY_TOTAL and spare[m]:
                    chosen.append((m, spare[m].pop()))
        counts = self._counts()
        cost = {m: sum(min(n, counts.get(fam, n)) for fam, n in self._module_needs(m).items()) for m in areas}
        return sorted(chosen, key=lambda c: (cost[c[0]], c[0], c[1]))

    def _bounty_requirements(self, n: int) -> typing.Dict[str, int]:
        """The tokens that holding n datapads needs: every one of the n easiest carriers' areas has to be reachable, so the largest need of each family among them."""
        merged: typing.Dict[str, int] = {}
        for module in {m for m, _ in self.bounty_carriers[:n]}:
            for fam, k in self._module_needs(module).items():
                merged[fam] = max(merged.get(fam, 0), k)
        return merged

    @staticmethod
    def _effective_cr(entry: typing.Dict[str, typing.Any]) -> float:
        """The rating a pool creature counts as in the difficulty rule: Force users count higher than their rating."""
        return entry["cr"] + (ENEMY_FORCE_USER_EXTRA if entry["category"] == "force_user" else 0.0)

    def _enemy_plan(self) -> typing.Dict[str, typing.Any]:
        """enemy_randomizer: which creature stands at each precomputed spawn point, {"spawns": [{module, x, y, z, angle, template, source}]}. Empty when the option
        is off. The difficulty rule: a creature must have a rating from (area's lowest - ENEMY_CR_TOLERANCE) up to (area's average + ENEMY_CR_HEADROOM), never above the
        area's highest non-boss rating, and those above the average are drawn less often (ENEMY_WEIGHT_SLOPE); if nothing in the pool fits, the weakest creatures of the
        pool are used rather than a strong one. (Until 2026-11-15 the ceiling was the area's highest non-boss rating, so every spot could get the strongest creature.)"""
        if not self.options.enemy_randomizer.value:
            return {}
        data = enemy_data()
        carriers = set(self.bounty_carriers)
        mode = self.options.enemy_mode.value
        pool = data["pool"]
        by_category: typing.Dict[str, typing.List[str]] = {}
        for resref, info in pool.items():
            by_category.setdefault(info["category"], []).append(resref)
        spawns = []
        for module in sorted(data["modules"]):
            info = data["modules"][module]
            if mode == ENEMY_AREA and info["category"] in by_category:
                base = by_category[info["category"]]
            else:
                base = list(pool)
            if mode == ENEMY_FULLY_RANDOM:
                candidates = base
            else:
                average = info.get("cr_avg", info["cr_cap"])
                ceiling = min(info["cr_cap"], math.ceil(average + ENEMY_CR_HEADROOM - 1e-9))
                candidates = [r for r in base if info["cr_min"] - ENEMY_CR_TOLERANCE <= pool[r]["cr"] and self._effective_cr(pool[r]) <= max(ceiling, info["cr_min"])]
                if not candidates:
                    weakest = sorted(base, key=lambda r: pool[r]["cr"])[:5]
                    candidates = weakest
            weights = [1.0] * len(candidates) if mode == ENEMY_FULLY_RANDOM else [
                1.0 / (1.0 + ENEMY_WEIGHT_SLOPE * max(0.0, self._effective_cr(pool[r]) - info.get("cr_avg", info["cr_cap"]))) for r in candidates]
            for index, (x, y, z) in enumerate(info["points"]):
                template = self.random.choices(candidates, weights=weights)[0]
                spawn = {"module": module, "x": x, "y": y, "z": z, "angle": round(self.random.uniform(0.0, 6.2832), 3), "template": template,
                         "source": pool[template]["source"]}
                if (module, index) in carriers:
                    spawn["bounty"] = 1                       # this creature carries a Bounty Datapad
                spawns.append(spawn)
        return {"spawns": spawns}

    def _loot_plan(self) -> typing.Dict[str, typing.Any]:
        """loot_randomizer: how the client changes the ordinary gear lying in containers and dropped by creatures. The pool is the shop pool (ordinary gear only, so
        quest and plot items are never touched); mode is loot_mode (replace, bonus or crafting; default changes nothing); the seed number makes every pick independent of the order of work. The opening
        module (101PER) is skipped because the first minutes of the game need the gear in it. Empty when the option is off."""
        if not self.options.loot_randomizer.value or self.options.loot_mode.value == LOOT_DEFAULT:
            return {}
        mode = {LOOT_REPLACE: "replace", LOOT_BONUS: "bonus", LOOT_CRAFTING: "crafting"}[self.options.loot_mode.value]
        return {"mode": mode, "pool": list(shop_data()["pool"]), "seed": self.random.getrandbits(32), "skip_modules": list(LOOT_SKIP_MODULES)}

    def _companion_prestige_pairs(self) -> typing.Dict[str, typing.List[int]]:
        """multiclass_companion prestige: the [light, dark] prestige pair each Jedi-capable companion's item applies; the game picks the side from the alignment
        when the item is used (the companion must be level 15 or more)."""
        if self.options.multiclass_companion.value != MULTICLASS_PRESTIGE:
            return {}
        return {str(slot): list(self.random.choice([(11, 14), (13, 16), (12, 15)])) for slot in JEDI_CAPABLE_SLOTS}

    def _companion_second_class(self) -> typing.Dict[str, int]:
        """multiclass_companion random_class: the second class each companion gets after level 15 (the game skips it when it equals their first class)."""
        if self.options.multiclass_companion.value != MULTICLASS_RANDOM:
            return {}
        return {str(slot): self.random.choice([0, 1, 2, 3, 4, 5, 9]) for slot in range(12) if slot not in (3, 5, 8)}

    def fill_slot_data(self) -> typing.Dict[str, typing.Any]:
        used = [l for l in LOCATIONS if self._location_used(l)]
